#!/usr/bin/env python3
"""Vendor the running Magpie web client, preserving its MIT license.

Only versioned application assets are copied; never cookies, boot preferences or
API data. Run explicitly after upgrading Magpie, then verify the read-only view.
"""
import concurrent.futures
import hashlib
import json
from pathlib import Path
import re
import sys
import urllib.request

ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
from svcdash.magpie import MAGPIE_URL,MAGPIE_PORT,_discover_magpie_key
OUT=ROOT/'static'/'magpie-native'


def main():
    key=_discover_magpie_key()
    def get(path):
        req=urllib.request.Request(MAGPIE_URL+'/'+path,headers={'Cookie':f'magpie_web_{MAGPIE_PORT}={key}'})
        with urllib.request.urlopen(req,timeout=20) as r:return r.read()
    html=get('').decode()
    assets=set(re.findall(r'(?:src|href)="([^"?#]+\.(?:js|css|svg|png))(?:\?[^"#]*)?"',html))
    assets.discard('boot.js')
    assets.update({'settingshints.js','phonetabs.js','pluginmd.js','quotaall.js'})
    # boot.js is generated by our adapter; it must never contain live preferences.
    OUT.mkdir(parents=True,exist_ok=True)
    def save(name):
        if name.startswith(('http:','https:','/')) or '..' in name.split('/'):return
        raw=get(name)
        if name.endswith('.js'):
            raw=raw.replace(b'/api/icons/',b'icons/')
        p=OUT/name;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(raw)
        return name,hashlib.sha256(raw).hexdigest()
    manifest={}
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        for value in pool.map(save,sorted(assets)):
            if value:manifest[value[0]]=value[1]
    # Classic scripts lazily import display helpers which are absent from HTML.
    # Their URLs are relative to the upstream application root.
    while True:
        pending=set()
        for name in manifest:
            if name.endswith('.js'):
                source=(OUT/name).read_text()
                pending.update(re.findall(r"import\(\s*[\"']\./([^\"']+\.js)[\"']",source))
        pending-=manifest.keys()
        if not pending:break
        with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
            for value in pool.map(save,sorted(pending)):
                if value:manifest[value[0]]=value[1]
    icon_names=set()
    def icons(value):
        if isinstance(value,dict):
            for k,v in value.items():
                if k=='icon' and isinstance(v,str):icon_names.add(v)
                else:icons(v)
        elif isinstance(value,list):
            for v in value:icons(v)
    for endpoint in ('state','providers','groups'):
        icons(json.loads(get('api/'+endpoint)))
    for name in icon_names:
        if name.startswith('file:'):
            ident=name[5:]
            if re.fullmatch(r'[a-f0-9]+\.(?:webp|png|svg)',ident):
                dest=OUT/'icons'/ident;dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(get('api/icons/'+ident))
        elif re.fullmatch(r'[a-zA-Z0-9_-]+',name):
            for ext in ('svg','png'):
                try: save('icons/'+name+'.'+ext);break
                except Exception: pass
    # The shared icon set is content-only; dynamic custom icons are copied by id.
    import shutil
    shutil.copytree(ROOT/'static'/'icons',OUT/'icons',dirs_exist_ok=True)
    (OUT/'LICENSE').write_text((ROOT.parent/'magpie'/'LICENSE').read_text())
    (OUT/'upstream.json').write_text(json.dumps({'source':'running Magpie web','assets':manifest},indent=2)+'\n')
    # Remove install-app artifacts and inject our transport before every upstream script.
    html=re.sub(r'<link[^>]+rel="manifest"[^>]*>','',html)
    html=html.replace('<script src="boot.js"></script>','<script src="snapshot.js"></script><script src="readonly.js"></script>')
    html=html.replace('</head>','<link rel="stylesheet" href="readonly.css"></head>')
    for asset in ('readonly.js','readonly.css','snapshot.js'):
        if (OUT/asset).exists():
            version=hashlib.sha256((OUT/asset).read_bytes()).hexdigest()[:12]
            html=html.replace('"'+asset+'"','"'+asset+'?v='+version+'"')
    for asset,digest in manifest.items():
        html=re.sub(re.escape(asset)+r'\?v=[0-9a-f]+',asset+'?v='+digest[:12],html)
    (OUT/'index.html').write_text(html)
    print('vendored',len(manifest),'assets')

if __name__=='__main__':main()
